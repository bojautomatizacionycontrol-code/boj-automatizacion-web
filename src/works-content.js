/** All published works share stable positions and photographs across languages. */
export function getWorkProjects(language = "es") {
  const locale = Object.hasOwn(translations, language) ? language : "es";
  return spanishProjects.map((original, index) => {
    const source = { ...original, ...spanishUpdates[index] };
    const copy = translations[locale]?.[index] || {};
    const project = { ...source, ...copy };
    const photo = source.photo || (index === 0 ? trainPhoto : undefined);
    const photoAlt = project.photoAlt || project.title;
    const supportPhotos = galleryPhotos
      .filter((image) => image.sourceIndex === index)
      .map((image) => ({ src: image.src, width: image.width, height: image.height, crop: image.crop, ...image[locale] }));
    return {
      ...project,
      sourceIndex: index,
      relatedWorks: project.relatedWorks || [],
      photo,
      photoAlt,
      realPhoto: Boolean(photo),
      // BT40 renders its established four photographs separately; these are its extras.
      photos: index === 0 ? supportPhotos : [
        ...(photo ? [{ src: photo, alt: photoAlt, caption: project.photoCaption || project.title }] : []),
        ...supportPhotos,
      ],
    };
  });
}
